// The codebook renderer, ported from backend/dhruva/codec/codebook.py's
// decode_reason() and render(). Proven against the same 500-capsule corpus
// decode.test.ts uses, across all twelve languages.

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { decodeCapsule } from "./decode";
import { LANGUAGES, renderReason } from "./codebook";

interface CorpusRow {
  id: string;
  capsule: Record<string, unknown>;
  hex: string;
  base32: string;
}

const corpus: CorpusRow[] = readFileSync("../eval/capsule_corpus.jsonl", "utf8")
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line));

const SLOT = /\{[a-z_]+\}/;

describe("codebook render", () => {
  it("knows all twelve languages", () => {
    expect(LANGUAGES).toHaveLength(12);
  });

  it("renders every corpus capsule in all twelve languages with no unfilled slots", () => {
    for (const row of corpus) {
      const capsule = decodeCapsule(row.base32);
      for (const lang of LANGUAGES) {
        const out = renderReason(capsule, lang);
        expect(out.text.length).toBeGreaterThan(0);
        expect(out.text).not.toMatch(SLOT);
      }
    }
  });

  it("does not degrade a coherent, reachable capsule", () => {
    // The corpus is random round-trip fuzzing data, not semantically valid
    // advisories — nothing guarantees an arbitrary row's reason_code band
    // matches its risk_class (most don't). Construct one deliberately instead:
    // band=no_go(2), family=wave(1), modifier=none(0) is reachable, and
    // risk_class "no_go" is band 2 — coherent by construction.
    const capsule = { ...decodeCapsule(corpus[0].base32), risk_class: "no_go", reason_code: 0b10_001_000 };
    const out = renderReason(capsule, "en");
    expect(out.degraded).toBe(false);
  });

  it("degrades to the worse band when reason_code disagrees with risk_class", () => {
    const capsule = decodeCapsule(corpus[0].base32);
    // Claim safe/wave/none while the capsule's own risk_class says "unknown" —
    // UNKNOWN outranks SAFE in the risk engine's severity order, so the
    // resolved band must be "unknown", not "safe".
    const damaged = { ...capsule, reason_code: 0b00_001_000 };
    const out = renderReason(damaged, "en");
    expect(out.degraded).toBe(true);
  });

  it("speaks a saturated reading as 'at least', never as an exact number", () => {
    const capsule = { ...decodeCapsule(corpus[0].base32), risk_class: "no_go", wave_hs_m: 7.75 };
    // band=no_go(2), family=wave(1), modifier=saturated(1)
    const withSaturatedWave = { ...capsule, reason_code: 0b10_001_001 };
    const out = renderReason(withSaturatedWave, "en");
    expect(out.text.toLowerCase()).toContain("at least");
  });

  it("renders byte-identically to Python across all languages for all 500 corpus capsules", () => {
    // This file is generated by Python's test_every_corpus_capsule_renders_in_every_language
    const parityDump: Record<string, Record<string, string>> = JSON.parse(
      readFileSync("../eval/render_parity.json", "utf8")
    );
    for (const row of corpus) {
      const expectedRenders = parityDump[row.id];
      expect(expectedRenders).toBeDefined();
      const capsule = decodeCapsule(row.base32);
      for (const lang of LANGUAGES) {
        const out = renderReason(capsule, lang);
        expect(out.text).toBe(expectedRenders[lang]);
      }
    }
  });
});
